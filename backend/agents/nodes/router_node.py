"""
QForge — ROUTER NODE
Responsibilities:
  1. Parse raw input with AST service to extract structure metadata
  2. Retrieve relevant enterprise guideline chunks from FAISS
  3. Ask local Ollama model to classify complexity (score 0-10)
  4. Decide routing path: local (Ollama) or cloud (Gemini)
  5. Emit telemetry event over the WebSocket channel
"""
import json
import logging
from backend.agents.state import AgentState
from backend.agents.prompts.routing_prompts import ROUTER_PROMPT
from backend.services.llm.ollama_client import OllamaClient
from backend.services.ast_parser.python_parser import parse_python
from backend.services.ast_parser.sql_parser import parse_sql
from backend.services.ast_parser.universal_parser import parse_universal
from backend.services.llm.gemini_client import GeminiClient
from backend.services.vector_store.faiss_store import FaissVectorStore
from backend.config import settings

logger = logging.getLogger(__name__)


def _compute_ast_complexity(fingerprint: dict, lang: str) -> int:
    """Calculate deterministic baseline complexity from AST fingerprint."""
    if lang == "python":
        func_cnt = fingerprint.get("function_count", 0)
        class_cnt = fingerprint.get("class_count", 0)
        async_cnt = fingerprint.get("async_function_count", 0)
        decorators = fingerprint.get("decorator_count", 0)
        score = 2 + (func_cnt * 1) + (class_cnt * 3) + (async_cnt * 2) + (decorators * 1)
        return min(max(score, 2), 9)
    elif lang == "sql":
        tables = fingerprint.get("table_count", 1)
        joins = fingerprint.get("join_count", 0)
        subqueries = fingerprint.get("subquery_count", 0)
        aggs = fingerprint.get("aggregation_count", 0)
        score = 2 + (tables * 1) + (joins * 2) + (subqueries * 3) + (aggs * 1)
        return min(max(score, 2), 9)
    return 5


async def router_node(state: AgentState, vector_store: FaissVectorStore) -> dict:
    """
    LangGraph node: Analyzes input, scores complexity, decides routing path.
    Returns a partial state dict that LangGraph merges into AgentState.
    """
    logger.info(f"[ROUTER] Session {state['session_id']} — starting analysis")
    audit = list(state.get("audit_notes", []))
    audit.append("ROUTER: Starting AST parsing and complexity analysis")

    # ── Step 1: AST Fingerprinting ─────────────────────────────
    raw_input = state["raw_input"]
    lang = state.get("language", "python")

    try:
        if lang == "python":
            fingerprint = parse_python(raw_input)
        elif lang == "sql":
            fingerprint = parse_sql(raw_input)
        else:
            fingerprint = parse_universal(raw_input, lang)
        audit.append(f"ROUTER: AST fingerprint extracted — type={fingerprint.get('code_type', lang)}")
    except Exception as e:
        fingerprint = {"error": str(e), "code_type": lang}
        audit.append(f"ROUTER: AST parse warning — {e}")

    # ── Step 2: RAG Guideline Retrieval ───────────────────────
    try:
        chunks = vector_store.search(raw_input, top_k=settings.top_k_retrieval)
        audit.append(f"ROUTER: Retrieved {len(chunks)} guideline chunks from FAISS")
    except Exception as e:
        chunks = []
        audit.append(f"ROUTER: FAISS retrieval failed — {e}, proceeding without context")

    # ── Step 3: Complexity Classification & Hypothesis (Gemini primary -> Ollama fallback) ──
    prompt = ROUTER_PROMPT.format(raw_input=raw_input)
    classification = None
    reason = "Analysis complete"

    # Try Gemini first for hypothesis & thinking
    if settings.gemini_api_key:
        try:
            gemini_c = GeminiClient(model=settings.gemini_model)
            raw_response = await gemini_c.generate(prompt)
            cleaned = raw_response.strip().strip("```json").strip("```").strip()
            classification = json.loads(cleaned)
            reason = classification.get("complexity_reason", "Classified by Gemini cloud")
            audit.append(f"ROUTER: Initial hypothesis generated by Gemini ({settings.gemini_model})")
        except Exception as ge:
            logger.warning(f"[ROUTER] Gemini hypothesis failed/quota exceeded: {ge}. Falling back to local Ollama.")
            audit.append("ROUTER: Gemini hypothesis fallback -> using local Ollama (qwen)")

    # Fallback to local Ollama if Gemini failed or unavailable
    if not classification:
        try:
            client = OllamaClient(model=settings.ollama_router_model, timeout=25.0)
            raw_response = await client.generate(prompt)
            cleaned = raw_response.strip().strip("```json").strip("```").strip()
            classification = json.loads(cleaned)
            reason = classification.get("complexity_reason", "Classified by local Ollama")
            audit.append(f"ROUTER: Classified by local Ollama ({settings.ollama_router_model})")
        except Exception as oe:
            logger.warning(f"[ROUTER] Ollama fallback failed: {oe}. Using deterministic AST heuristics.")
            complexity_score = _compute_ast_complexity(fingerprint, lang)
            detected_lang = lang
            reason = f"Calculated from AST metrics (fallback: {oe})"
            code_type = fingerprint.get("code_type", lang)
            classification = None

    if classification:
        complexity_score = int(classification.get("complexity_score", 5))
        detected_lang = classification.get("language", lang)
        code_type = classification.get("code_type", fingerprint.get("code_type", lang))

    # ── Step 4: Routing Decision ──────────────────────────────
    routing_path = "cloud" if complexity_score >= settings.complexity_threshold else "local"
    audit.append(
        f"ROUTER: complexity={complexity_score}/10 → path={routing_path.upper()} | "
        f"type={code_type} | reason={reason}"
    )

    logger.info(
        f"[ROUTER] Done — score={complexity_score}, path={routing_path}, lang={detected_lang}"
    )

    return {
        "language": detected_lang,
        "complexity_score": complexity_score,
        "routing_path": routing_path,
        "ast_fingerprint": fingerprint,
        "context_chunks": chunks,
        "audit_notes": audit,
    }
